#!/usr/bin/env bash
# Remove the Daksha Python environment created by install.sh.
#
#   - the venv                   (default ~/daksha_venv)
#   - ~/activate_daksha.sh       (only if install.sh generated it)
#   - the `source ~/activate_daksha.sh` line install.sh --bashrc added
#   - with --uv: uv itself (~/.local/bin/uv, uvx) and its cache
#
# Nothing else is touched: the workspace, ROS and ~/.local are left alone.
#
#   src/robot_setup/scripts/uninstall.sh
#   ros2 run robot_setup uninstall.sh --yes
#
# Options:
#   --venv DIR     venv to remove       (default: $DAKSHA_VENV or ~/daksha_venv)
#   --venv-only    remove only the venv (keep the activation script and ~/.bashrc line)
#   --uv           also remove uv and its cache
#   -y, --yes      don't ask for confirmation
#   -h, --help     show this help

set -euo pipefail

VENV="${DAKSHA_VENV:-$HOME/daksha_venv}"
VENV_ONLY=0
REMOVE_UV=0
YES=0

usage() { sed -n '2,/^$/{s/^# \{0,1\}//;p}' "$0"; }

while [ $# -gt 0 ]; do
    case "$1" in
        --venv)      VENV="$2"; shift 2 ;;
        --venv-only) VENV_ONLY=1; shift ;;
        --uv)        REMOVE_UV=1; shift ;;
        -y|--yes)    YES=1; shift ;;
        -h|--help)   usage; exit 0 ;;
        *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
    esac
done

die() { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

ACTIVATE="$HOME/activate_daksha.sh"
BASHRC="$HOME/.bashrc"
BASHRC_LINE="source \"$ACTIVATE\""
BASHRC_COMMENT="# Daksha robot environment (robot_setup)"
UV_BIN="$HOME/.local/bin"

# --- Work out what to remove -------------------------------------------------
targets=()
if [ -e "$VENV" ]; then
    # Only ever delete something that really is a venv.
    [ -f "$VENV/pyvenv.cfg" ] || die "$VENV exists but is not a venv (no pyvenv.cfg) - not removing it"
    targets+=("venv:        $VENV")
fi
if [ "$VENV_ONLY" -eq 0 ]; then
    if [ -f "$ACTIVATE" ]; then
        if grep -q "Generated by robot_setup" "$ACTIVATE"; then
            targets+=("script:      $ACTIVATE")
        else
            echo "skipping $ACTIVATE: not generated by robot_setup"
        fi
    fi
    grep -qxF "$BASHRC_LINE" "$BASHRC" 2>/dev/null && targets+=("~/.bashrc:   $BASHRC_LINE")
fi
if [ "$REMOVE_UV" -eq 1 ]; then
    [ -e "$UV_BIN/uv" ] && targets+=("uv:          $UV_BIN/uv, $UV_BIN/uvx")
    [ -d "$HOME/.cache/uv" ] && targets+=("uv cache:    $HOME/.cache/uv")
fi

if [ ${#targets[@]} -eq 0 ]; then
    echo "Nothing to remove."
    exit 0
fi

echo "Will remove:"
printf '  %s\n' "${targets[@]}"
if [ "$YES" -eq 0 ]; then
    read -r -p "Continue? [y/N] " answer
    [[ "$answer" =~ ^[Yy]$ ]] || { echo "Aborted."; exit 1; }
fi

# --- Remove ------------------------------------------------------------------
if [ -e "$VENV" ]; then
    rm -rf -- "$VENV"
    echo "removed $VENV"
fi
if [ "$VENV_ONLY" -eq 0 ]; then
    if [ -f "$ACTIVATE" ] && grep -q "Generated by robot_setup" "$ACTIVATE"; then
        rm -f -- "$ACTIVATE"
        echo "removed $ACTIVATE"
    fi
    if grep -qxF "$BASHRC_LINE" "$BASHRC" 2>/dev/null; then
        cp "$BASHRC" "$BASHRC.daksha.bak"
        # Drop the line and the comment install.sh wrote above it.
        grep -vxF -e "$BASHRC_LINE" -e "$BASHRC_COMMENT" "$BASHRC.daksha.bak" > "$BASHRC"
        echo "removed the line from ~/.bashrc (backup: ~/.bashrc.daksha.bak)"
    fi
fi
if [ "$REMOVE_UV" -eq 1 ]; then
    if command -v uv >/dev/null || [ -x "$UV_BIN/uv" ]; then
        "${UV_BIN}/uv" cache clean 2>/dev/null || true
    fi
    rm -rf -- "$HOME/.cache/uv"
    rm -f -- "$UV_BIN/uv" "$UV_BIN/uvx"
    echo "removed uv (the PATH line the uv installer added to your shell profile is left in place; it is harmless)"
fi

echo "Done."
# This script runs in a child process, so it cannot deactivate the shell that
# started it. Tell the user how, if the removed venv is still active there.
# (daksha_uninstall, defined by activate_daksha.sh, does this automatically.)
if [ -z "${DAKSHA_DEACTIVATES_AFTER:-}" ] && [ -n "${VIRTUAL_ENV:-}" ] \
        && [ "$VIRTUAL_ENV" = "$VENV" -o "$(basename "$VIRTUAL_ENV")" = "$(basename "$VENV")" ]; then
    printf '\n\033[1;33mThe removed venv is still active in this terminal.\033[0m A script cannot\n'
    printf 'change the shell that runs it, so leave it yourself:\n'
    printf '    deactivate_daksha     (or: deactivate, or open a new terminal)\n'
    printf 'Next time, use  daksha_uninstall  to remove and deactivate in one step.\n'
fi
